def as_frame(entries: Iterable[CatalogEntry] | None = None) -> pd.DataFrame:
    entries = list(entries if entries is not None else CATALOG)
    return pd.DataFrame(
        [
            {
                "section": e.section,
                "chapter": e.chapter_title,
                "title": e.title,
                "status": e.status,
                "strategies": ", ".join(e.strategy_keys),
                "requires": e.requires,
                "note": e.note,
            }
            for e in entries
        ]
    )


def runnable() -> list[CatalogEntry]:
    return [e for e in CATALOG if e.is_runnable]


def by_section(section: str) -> CatalogEntry:
    for entry in CATALOG:
        if entry.section == section:
            return entry
    raise KeyError(f"no catalog entry for section {section}")


def summary() -> pd.DataFrame:
    """Per-chapter counts of implemented / substituted / not-implemented."""
    frame = as_frame()
    pivot = (
        frame.pivot_table(index="chapter", columns="status", values="section", aggfunc="count")
        .fillna(0)
        .astype(int)
    )
    pivot["total"] = pivot.sum(axis=1)
    return pivot.sort_values("total", ascending=False)
