"""Catalog of every numbered strategy in Kakushadze & Serur (SSRN 3247865).

The paper is marketed as "151 trading strategies"; its table of contents carries
175 numbered ``Strategy:`` entries once sub-strategies (2.40.1, 3.9.1, 10.3.1,
...) are counted individually.  All of them are listed here so the research
track covers the whole paper, each tagged with what it would take to run:

``implemented``
    Reproduced from the paper's formulas using ``stooq.daily`` OHLCV bars.
``substituted``
    Reproduced, but with a documented proxy for an input this universe lacks
    (a factor file, an ETF leg, an open-interest series).  ``note`` says what.
``not_implemented``
    Needs data outside daily equity bars.  ``requires`` says what.
"""

